export const ARGUMENT_EXTRACTOR = `
وحدة بناء الحجة: صغ كل استنتاج على هيئة سلسلة صريحة:
الآية ← الملاحظة اللغوية ← الافتراض ← الاستنتاج.
ثم اسأل عن كل افتراض: هل هو موجود في النص فعلًا، أم أُضيف بين النص والنتيجة؟
اذكر الافتراضات المضافة صراحة في حقل assumptions.
`.trim();

export const COUNTER_ARGUMENT_GENERATOR = `
وحدة الاعتراض: بعد كل استنتاج مهم، ابحث داخل القرآن عن أقوى الآيات أو الاستعمالات
التي قد تُضعف هذا الاستنتاج، واعرضها بأمانة حتى لو نقضت ما رجّحته،
ثم بيّن سبب الترجيح الحالي إن بقي راجحًا.
`.trim();

export const EVIDENCE_SCORER = `
وحدة تصنيف قوة العلاقة بالنص (directness). صنّف كل استنتاج بواحد من:
A: النتيجة مذكورة في النص بصورة مباشرة جدًا.
B: استنتاج سياقي قوي بخطوة واحدة.
C: استنتاج تفسيري يحتاج ترجيح معنى من معانٍ.
D: استنتاج متعدد الخطوات.
E: يعتمد على مقدمة غير مستخرجة من القرآن.
هذا التصنيف يقيس مدى مباشرة العلاقة بالنص فقط: A ليست بمعنى "صحيح"، وE ليست بمعنى "خطأ".
`.trim();

export const FINAL_SYNTHESIZER = `
وحدة الصياغة النهائية: اجمع ما سبق في كائن JSON واحد مطابق للمخطط المطلوب،
بخلاصة قصيرة جدًا في أولها. لا تُخرج أي نص خارج JSON.
`.trim();

/** Modules merged into the single MVP call, in order. */
export const MVP_MODULES = [
  QUESTION_ANALYZER,
  CONTEXT_ANALYZER,
  ARGUMENT_EXTRACTOR,
  COUNTER_ARGUMENT_GENERATOR,
  EVIDENCE_SCORER,
  FINAL_SYNTHESIZER,
];

export function buildSystemPrompt(): string {
  return [SHARED_RULES, '', 'الوحدات التي تنفّذها في هذا الطلب:', ...MVP_MODULES].join('\n\n');
}
