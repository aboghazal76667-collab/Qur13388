/**
 * Prompt architecture.
 *
 * Rather than one enormous system prompt, the analysis is expressed as named
 * modules that mirror the pipeline stages. For the MVP two of them are merged
 * into a single call to keep latency and cost sane, but each module keeps its
 * own text so it can be split out — or swapped for a different model — without
 * rewriting the others.
 */

